//! The antipattern lists of `AgreementRule` (`AgreementRuleAntiPatterns1/2/3`)
//! and `AgreementRule2`, translated from the pinned Java sources with a
//! one-off generator (`/tmp/kilo/gen-de-agreement-antipatterns.py`; the
//! output is committed). The helper names mirror the Java DSL:
//! `token`/`cs_token`/`token_regex`/`cs_regex`/`pos`/`pos_regex`,
//! `with_text` (pattern token with both a POS tag and a text/regex),
//! `inflected` (`matchInflectedForms`), `skip`/`min0`/`min_n`/`max_n`,
//! `negate`, `spacebefore_false`, `with_string_exception`
//! (`posRegexWithStringException`) and `token_empty`.

use lt_pattern::{ExceptionSpec, PatternToken};

pub(crate) fn token(text: &str) -> PatternToken {
    PatternToken {
        text: Some(text.to_string()),
        in_marker: true,
        ..Default::default()
    }
}

pub(crate) fn cs_token(text: &str) -> PatternToken {
    PatternToken {
        text: Some(text.to_string()),
        case_sensitive: true,
        case_sensitive_set: true,
        in_marker: true,
        ..Default::default()
    }
}

pub(crate) fn token_regex(text: &str) -> PatternToken {
    PatternToken {
        text: Some(text.to_string()),
        regexp: true,
        in_marker: true,
        ..Default::default()
    }
}

pub(crate) fn cs_regex(text: &str) -> PatternToken {
    PatternToken {
        text: Some(text.to_string()),
        regexp: true,
        case_sensitive: true,
        case_sensitive_set: true,
        in_marker: true,
        ..Default::default()
    }
}

pub(crate) fn pos(postag: &str) -> PatternToken {
    PatternToken {
        postag: Some(postag.to_string()),
        in_marker: true,
        ..Default::default()
    }
}

pub(crate) fn pos_regex(postag: &str) -> PatternToken {
    PatternToken {
        postag: Some(postag.to_string()),
        postag_regexp: true,
        in_marker: true,
        ..Default::default()
    }
}

/// `PatternTokenBuilder`: a POS element that also carries a text matcher.
pub(crate) fn with_text(mut base: PatternToken, text: PatternToken) -> PatternToken {
    base.text = text.text;
    base.regexp = text.regexp;
    base.case_sensitive = text.case_sensitive;
    base.case_sensitive_set = text.case_sensitive_set;
    base.inflected = text.inflected;
    base.negate = text.negate;
    base
}

/// `posRegexWithStringException`: the token exception is a case-sensitive
/// regexp on the token text.
pub(crate) fn with_string_exception(mut base: PatternToken, regex: &str) -> PatternToken {
    base.exceptions.push(ExceptionSpec {
        text: Some(regex.to_string()),
        regexp: true,
        ..Default::default()
    });
    base
}

pub(crate) fn inflected(mut t: PatternToken) -> PatternToken {
    t.inflected = true;
    t
}

pub(crate) fn negate(mut t: PatternToken) -> PatternToken {
    t.negate = true;
    t
}

pub(crate) fn skip(mut t: PatternToken, value: i32) -> PatternToken {
    t.skip = Some(value);
    t
}

pub(crate) fn min0(mut t: PatternToken) -> PatternToken {
    t.min = Some(0);
    t
}

#[allow(dead_code)]
pub(crate) fn min_n(mut t: PatternToken, value: i32) -> PatternToken {
    t.min = Some(value);
    t
}

pub(crate) fn max_n(mut t: PatternToken, value: i32) -> PatternToken {
    t.max = Some(value);
    t
}

pub(crate) fn spacebefore_false(mut t: PatternToken) -> PatternToken {
    t.spacebefore = Some(false);
    t
}

pub(crate) fn token_empty() -> PatternToken {
    PatternToken {
        in_marker: true,
        ..Default::default()
    }
}

